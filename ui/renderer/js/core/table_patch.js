// Retain row/cell identity. Only changed cell contents and attributes mutate.
export function patchRow(node, fresh) {
  for (const attr of [...node.attributes]) if (!fresh.hasAttribute(attr.name)) node.removeAttribute(attr.name);
  for (const attr of fresh.attributes) if (node.getAttribute(attr.name) !== attr.value) node.setAttribute(attr.name, attr.value);
  if (node.cells.length !== fresh.cells.length) { node.replaceChildren(...fresh.children); return node; }
  [...fresh.cells].forEach((cell, index) => {
    const current = node.cells[index];
    for (const attr of [...current.attributes]) if (!cell.hasAttribute(attr.name)) current.removeAttribute(attr.name);
    for (const attr of cell.attributes) if (current.getAttribute(attr.name) !== attr.value) current.setAttribute(attr.name, attr.value);
    if (current.innerHTML !== cell.innerHTML) current.innerHTML = cell.innerHTML;
  });
  return node;
}

export function rowFromHtml(html) {
  const template = document.createElement('template');
  template.innerHTML = html.trim();
  return template.content.firstElementChild;
}

// Table cells here are generated by the shared renderers (no nested tables).
// Compare source markup before asking Chromium to parse unchanged cells.
export function patchCells(row, html) {
  const cells = html.match(/<td\b[^>]*>[\s\S]*?<\/td>/g) || [];
  if (row.cells.length !== cells.length) {
    row.innerHTML = html;
  } else {
    cells.forEach((markup,index)=>{
      if (row._cellMarkup?.[index] === markup) return;
      const current=row.cells[index], fresh=rowFromHtml(markup);
      for(const attr of [...current.attributes]) if(!fresh.hasAttribute(attr.name)) current.removeAttribute(attr.name);
      for(const attr of fresh.attributes) if(current.getAttribute(attr.name)!==attr.value)current.setAttribute(attr.name,attr.value);
      if(current.innerHTML!==fresh.innerHTML)current.innerHTML=fresh.innerHTML;
    });
  }
  row._cellMarkup=cells;
}
