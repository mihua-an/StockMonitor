import assert from 'node:assert/strict';
import {beginSelection,selectionMark,selectionStage,selectionPayload,selectionComponentPaint,selectionTraceSnapshot} from '../ui/renderer/js/core/selection_latency_trace.js';
const a=beginSelection('2330');
selectionMark('2330','renderer_request_sent',a);
const b=beginSelection('2317');
selectionPayload('2330','trades',[{}],a);
selectionStage('2317','bridge',{queue_ms:4},b);
assert.equal(selectionTraceSnapshot().rows[0].channels.trades,undefined);
assert.equal(selectionTraceSnapshot().rows[1].from_code,'2330');
assert.equal(selectionTraceSnapshot().stagePercentiles['bridge.queue_ms'].p95,4);
const frames=[]; globalThis.requestAnimationFrame=fn=>frames.push(fn);
const host={isConnected:true,getClientRects:()=>[{}]};
for(let i=0;i<100;i++) selectionComponentPaint('2317','trades',host);
assert.equal(frames.length,1,'paint trace must not add one callback per Tick');
frames.shift()(); frames.shift()();
assert.ok(selectionTraceSnapshot().rows[1].marks.trades_painted>=0);
beginSelection('2330');
assert.equal(selectionTraceSnapshot().rows[2].selection_generation,3);
assert.equal(selectionTraceSnapshot().rows[2].marks.trades_painted,undefined);
for(let i=0;i<150;i++)beginSelection(String(i));
assert.equal(selectionTraceSnapshot().rows.length,128);
console.log('Selection trace identity, bounded history, stage percentiles and paint coalescing passed');
