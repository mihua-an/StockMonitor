import assert from 'node:assert/strict';
import {beginSelection,selectionMark} from '../ui/renderer/js/core/selection_latency_trace.js';
import {installSelectionScenarioRunner} from '../ui/renderer/js/features/realtime/selection_scenario_runner.js';
globalThis.window={};
const selected=[];
const resident=new Set(['2317']);
const runner=installSelectionScenarioRunner({select:code=>{selected.push(code);resident.add(code);const trace=beginSelection(code);selectionMark(code,'first_meaningful_market_data',trace);setTimeout(()=>selectionMark(code,'trend_painted',trace),120);},cacheProbe:code=>resident.has(code)});
const result=await runner.run({scenario:'A_B_A',intervalMs:100,settleMs:10,loadProfile:'LOW'});
assert.deepEqual(selected,['2330','2317','2330']);
assert.deepEqual(result.rows.map(row=>row.renderer_cache_class),['COLD','WARM','HOT']);
assert.ok(result.rows.every(row=>row.run_id===result.run_id));
assert.equal(result.evidence_class,'selection_scenario');
assert.deepEqual(runner.lastResult().rows,result.rows);
assert.equal(runner.downloadLast(),false);
const second=await runner.run({codes:['2330','8271'],intervalMs:100,settleMs:80});
assert.equal(second.skipped.length,1,'same-symbol selection must not reuse an old generation');
assert.equal(second.rows.length,1);
assert.equal(second.percentiles.first_meaningful_market_data.samples,1,'percentiles must be scoped to this run');
assert.ok(second.rows[0].marks.trend_painted>=120,'settling must capture slower component paint');
assert.equal(result.rows[0].run_id,result.run_id,'subsequent run must not relabel old traces');
await assert.rejects(()=>runner.run({scenario:'RAPID_FIVE',intervalMs:42}),/intervalMs/);
console.log('Selection scenario sequence, cache classification and correlation passed');
