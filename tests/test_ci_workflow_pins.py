"""CI runs only code it pinned: third-party actions by commit (a tag can be moved to other code), Python packages from
hash-checked locks (ruff is in requirements/test.lock, generated by scripts/tooling/lock_dependencies.py)."""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WORKFLOW = ROOT / ".github" / "workflows" / "ci.yml"
PINNED_ACTION = re.compile(r"^\s*-?\s*uses:\s*[\w.-]+/[\w./-]+@[0-9a-f]{40}\s+#\s*v\d+\.\d+\.\d+\s*$")


def _steps():
    data = yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))
    return [step for job in data["jobs"].values() for step in job["steps"]]


def test_every_action_is_pinned_to_a_commit_with_its_release_in_a_comment():
    lines = [line for line in WORKFLOW.read_text(encoding="utf-8").splitlines() if re.match(r"^\s*-?\s*uses:", line)]
    assert lines, "the workflow uses no action?"
    for line in lines:
        assert PINNED_ACTION.match(line), line


def test_every_pip_install_is_hash_checked():
    for step in _steps():
        for line in step.get("run", "").splitlines():
            if "pip install" in line:
                assert "--require-hashes" in line and "-r requirements/" in line, line


def test_the_lint_runs_the_ruff_of_the_test_lock():
    lint = next(step for step in _steps() if step.get("name") == "Lint (Python)")
    assert lint["run"].split("#")[0].strip() == "python -m ruff check ."
    install = next(step for step in _steps() if step.get("name") == "Python dependencies (hash-checked locks)")
    assert "-r requirements/test.lock" in install["run"]
    lock = (ROOT / "requirements" / "test.lock").read_text(encoding="utf-8")
    pin = re.search(r"^ruff==(\S+) \\\n\s+--hash=sha256:[0-9a-f]{64}", lock, re.MULTILINE)
    assert pin, "ruff is not pinned with a hash in requirements/test.lock"
    assert f"ruff=={pin.group(1)}" in (ROOT / "requirements" / "test.in").read_text(encoding="utf-8").splitlines()
