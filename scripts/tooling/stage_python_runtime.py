"""Stage a redistributable, self-contained Python runtime for packaged mode.

Produces packaging/python/ (gitignored, a build artifact like dist/ or native/*/target/ -- not committed):
  - the official python.org embeddable CPython named in requirements/python-bootstrap.json, checked against its
    pinned sha256, patched to enable Lib/site-packages and to add the packaged app-runtime root (one
    directory up) to sys.path;
  - pip, installed from a pinned, sha256-checked wheel (not the moving get-pip.py). It stays in the runtime: the
    installer does not ship the broker SDKs, the user installs them with this pip (see below);
  - every package pinned in requirements/core.lock and models.lock (the Health-launched training job needs the
    model chain), installed from PyPI wheels only (--only-binary=:all:) and checked against the locks' sha256
    hashes (--require-hashes), isolated from the host's own site-packages;
  - provider_sdk/<provider>.txt: the hash-pinned requirement lines the user installs with
    install_provider_sdk.ps1 -- the provider lock's packages that the bundle does not already contain;
  - sitecustomize.py: appends the per-user provider SDK directory to sys.path;
  - STAGED_RUNTIME.json: what was staged (versions, digests, the executables it contains).

Broker SDKs are NOT staged: shioaji and moomoo-api stay out of the installer until their redistribution
terms are confirmed. The user installs them into %APPDATA%\\StockMonitor\\provider-sdk (or
STOCK_MONITOR_PROVIDER_SDK_DIR); see docs/development/build_and_release.md.

Usage:
    python scripts/tooling/stage_python_runtime.py [--force]

Re-running rebuilds packaging/python/ from scratch (--force required if it already exists, to avoid silently
trusting a stale/partial prior run).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

# Two levels below the project root, like every entry script.
ROOT = Path(__file__).resolve().parents[2]
STAGE_DIR = ROOT / "packaging" / "python"
BOOTSTRAP_PINS = ROOT / "requirements" / "python-bootstrap.json"

# What the installer bundles. Provider SDK locks are only read to work out what the user has to add.
RUNTIME_LOCKS = ("core.lock", "models.lock")
PROVIDER_SDK_LOCKS = {"shioaji": "shioaji.lock", "futu": "futu.lock"}
# Never bundled, whatever a lock says; the staged runtime is checked for their absence.
PROVIDER_SDK_PACKAGES = {"shioaji": ("shioaji",), "futu": ("moomoo", "futu")}
PROVIDER_SDK_DISTRIBUTIONS = frozenset({"shioaji", "moomoo-api"})

# Executables the staged runtime may contain. pip keeps distlib's launcher templates (it writes console-script
# launchers from them when the user installs an SDK); anything else is a vendor tool that has no business in the
# installer.
ALLOWED_EXECUTABLES = ("python.exe", "pythonw.exe")
ALLOWED_EXECUTABLE_DIRS = (("Lib", "site-packages", "pip", "_vendor", "distlib"),)

_SITECUSTOMIZE_TEMPLATE = '''\
"""Generated by scripts/tooling/stage_python_runtime.py: make the user-installed broker SDKs importable.

The installer does not ship shioaji / moomoo-api. install_provider_sdk.ps1 installs each provider into a
version folder <root>/<provider>/v-<time> and names the active one in <root>/<provider>/active.txt: only
that folder is used -- one path component inside the provider's own folder -- so an interrupted or failed install
is never imported. Appended (not prepended) so the bundled packages always win.

A provider without active.txt is not installed. Anything else that stops its folder from being used (the file
cannot be read, names no valid folder, the folder is missing) is written to stderr and kept in
PROVIDER_SDK_ERRORS, which the SDK status probe reports: the provider then fails to import with that reason known,
never as "not installed".
"""
import os
import sys

PROVIDER_SDK_ERRORS = {}
_sdk_dir = os.environ.get("STOCK_MONITOR_PROVIDER_SDK_DIR") or os.path.join(
    os.environ.get("APPDATA") or os.path.join(os.path.expanduser("~"), "AppData", "Roaming"),
    *__PROVIDER_SDK_DIR__)
for _provider in ("shioaji", "futu"):
    _root = os.path.join(_sdk_dir, _provider)
    try:
        with open(os.path.join(_root, "active.txt"), encoding="ascii") as _handle:
            _name = _handle.read().strip()
    except FileNotFoundError:  # not an error: that provider's SDK is not installed
        continue
    except (OSError, UnicodeDecodeError) as _exc:
        PROVIDER_SDK_ERRORS[_provider] = f"reading {os.path.join(_root, 'active.txt')} failed: {type(_exc).__name__}: {_exc}"
    else:
        _active = os.path.join(_root, _name)
        if not _name or _name != os.path.basename(_name) or _name in (".", ".."):
            PROVIDER_SDK_ERRORS[_provider] = f"{os.path.join(_root, 'active.txt')} names no version folder: {_name!r}"
        elif not os.path.isdir(_active):
            PROVIDER_SDK_ERRORS[_provider] = f"the active version folder {_active} does not exist"
        elif _active not in sys.path:
            sys.path.append(_active)
    if _provider in PROVIDER_SDK_ERRORS:
        sys.stderr.write(f"[PROVIDER SDK] {_provider}: {PROVIDER_SDK_ERRORS[_provider]}\\n")
'''

# The default SDK root is the installed flavor's (config/var_layout.json, through installed_flavor.py), never a
# second hand-written name.
sys.path.insert(0, str(ROOT))
from scripts.tooling.installed_flavor import provider_sdk_dir  # noqa: E402

SITECUSTOMIZE = _SITECUSTOMIZE_TEMPLATE.replace("__PROVIDER_SDK_DIR__", repr(tuple(provider_sdk_dir())))


def _log(message: str) -> None:
    print(f"[stage_python_runtime] {message}", flush=True)


def _run(args: list[str], **kwargs) -> None:
    _log("+ " + " ".join(args))
    subprocess.run(args, check=True, **kwargs)


def _isolated_env() -> dict[str, str]:
    env = {**os.environ, "PYTHONNOUSERSITE": "1"}
    for name in ("PYTHONPATH", "PYTHONHOME", "PYTHONSTARTUP"):
        env.pop(name, None)
    return env


def _pins() -> dict:
    return json.loads(BOOTSTRAP_PINS.read_text(encoding="utf-8"))


def _target_python_version() -> str:
    evidence = json.loads((ROOT / "requirements" / "environment-evidence.json").read_text(encoding="utf-8"))
    version = str(evidence.get("python") or "").strip()
    if not version or version.count(".") != 2:
        raise RuntimeError(
            f"requirements/environment-evidence.json has no usable 'python' version field (got {version!r})")
    if str(evidence.get("platform") or "") != "win32" or str(evidence.get("machine") or "") != "AMD64":
        raise RuntimeError(
            "environment-evidence.json was not captured on Windows x64 (AMD64) -- "
            "this stager only supports that target, matching the rest of the toolchain evidence.")
    pinned = str(_pins()["python_embed"]["version"])
    if pinned != version:
        raise RuntimeError(
            f"requirements/python-bootstrap.json pins CPython {pinned} but environment-evidence.json records "
            f"{version}; update the pin (url and sha256) together with the evidence")
    return version


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _download_verified(url: str, sha256: str, dest: Path) -> None:
    _log(f"downloading {url}")
    with urllib.request.urlopen(url, timeout=120) as response, dest.open("wb") as stream:
        shutil.copyfileobj(response, stream)
    actual = _sha256(dest)
    if actual != sha256.lower():
        dest.unlink(missing_ok=True)
        raise RuntimeError(f"sha256 mismatch for {url}: expected {sha256}, got {actual}")
    _log(f"sha256 ok {actual}")


def _stage_interpreter(version: str) -> Path:
    if STAGE_DIR.exists():
        shutil.rmtree(STAGE_DIR)
    STAGE_DIR.mkdir(parents=True)
    pin = _pins()["python_embed"]
    zip_path = STAGE_DIR.with_suffix(".download.zip")
    try:
        _download_verified(pin["url"], pin["sha256"], zip_path)
        with zipfile.ZipFile(zip_path) as archive:
            archive.extractall(STAGE_DIR)
    finally:
        zip_path.unlink(missing_ok=True)

    major_minor = "".join(version.split(".")[:2])
    pth_file = STAGE_DIR / f"python{major_minor}._pth"
    if not pth_file.is_file():
        raise RuntimeError(f"expected {pth_file.name} in the embeddable distribution, not found")
    # Enable Lib/site-packages (embeddable distributions ship it disabled), and add ".." so the sibling app-runtime
    # tree (main.py, backend/, service/, config/ -- staged next to python/ by package.json's extraResources) is
    # importable with no PYTHONPATH wiring. A ._pth file suppresses the normal script-directory sys.path insertion,
    # so this is not optional. "." keeps sitecustomize.py (next to python.exe) importable.
    pth_file.write_text(
        f"python{major_minor}.zip\n.\nLib\\site-packages\n..\n\nimport site\n", encoding="utf-8")
    (STAGE_DIR / "sitecustomize.py").write_text(SITECUSTOMIZE, encoding="utf-8")
    return STAGE_DIR / "python.exe"


def _bootstrap_pip(python_exe: Path) -> None:
    pin = _pins()["pip_wheel"]
    wheel = STAGE_DIR / Path(pin["url"]).name
    _download_verified(pin["url"], pin["sha256"], wheel)
    try:
        # pip on Windows refuses to modify itself unless run as `python -m pip`, and a ._pth interpreter ignores
        # PYTHONPATH, so it cannot run from the wheel. A wheel is a plain archive: unpack it into site-packages,
        # then let that pip reinstall itself from the same verified file so it is recorded like any package.
        site_packages = STAGE_DIR / "Lib" / "site-packages"
        site_packages.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(wheel) as archive:
            archive.extractall(site_packages)
        _run([str(python_exe), "-m", "pip", "install", "--no-index", "--no-user", "--force-reinstall",
              "--no-warn-script-location", "--disable-pip-version-check", str(wheel)], env=_isolated_env())
    finally:
        wheel.unlink(missing_ok=True)


def _lock_entries(names) -> dict[str, str]:
    """{package: "name==version --hash=sha256:..."} across the given locks, one line per pin."""
    seen: dict[str, str] = {}
    for name in names:
        text = (ROOT / "requirements" / name).read_text(encoding="utf-8").replace("\\\n", " ")
        for line in text.splitlines():
            line = " ".join(line.split("#", 1)[0].split())
            if "==" not in line:
                continue
            if "--hash=sha256:" not in line:
                raise RuntimeError(f"requirements/{name}: {line} has no hash; run lock_dependencies.py --write")
            seen[line.partition("==")[0].strip().lower()] = line
    return seen


def _locked_entries() -> dict[str, str]:
    """What the installer bundles (never a provider SDK)."""
    entries = _lock_entries(RUNTIME_LOCKS)
    leaked = PROVIDER_SDK_DISTRIBUTIONS & set(entries)
    if leaked:
        raise RuntimeError(f"bundled locks pin a broker SDK ({', '.join(sorted(leaked))}); Q52 keeps them out")
    return entries


def _locked_requirements() -> list[str]:
    return sorted(_locked_entries().values())


def provider_sdk_requirements() -> dict[str, list[str]]:
    """Per provider: the package names the user installs, latest from PyPI -- its lock's closure minus what the bundle
    already carries, so `pip install --no-deps` of these names finds every other dependency in the bundled runtime.
    The names, not versions: the broker SDK is installed unpinned so the user always gets the newest one
    (decisions.md 券商 SDK 裝最新不綁版本). The lock still pins versions, but only to derive this name set and to
    check the bundle covers the rest; it is not what gets installed."""
    bundled = _locked_entries()
    out: dict[str, list[str]] = {}
    for provider, lock in PROVIDER_SDK_LOCKS.items():
        entries = _lock_entries((lock,))
        extra = [package for package in sorted(entries) if package not in bundled]
        for package, line in entries.items():
            if package in bundled and bundled[package].split()[0] != line.split()[0]:
                raise RuntimeError(f"{lock} pins {line.split()[0]} but the bundle has {bundled[package].split()[0]}")
        if not any(package in PROVIDER_SDK_DISTRIBUTIONS for package in extra):
            raise RuntimeError(f"{lock} has no broker SDK")
        out[provider] = extra
    return out


def _pip_install_locked(python_exe: Path) -> None:
    site_packages = STAGE_DIR / "Lib" / "site-packages"
    site_packages.mkdir(parents=True, exist_ok=True)
    requirements_file = STAGE_DIR / "_locked_requirements.txt"
    requirements_file.write_text("\n".join(_locked_requirements()) + "\n", encoding="utf-8")
    try:
        _run([
            str(python_exe), "-m", "pip", "install",
            "--no-user", "--target", str(site_packages),
            "-r", str(requirements_file),
            "--only-binary=:all:", "--require-hashes",
        ], env=_isolated_env())
    finally:
        requirements_file.unlink(missing_ok=True)


def _provider_sdk_file_text(provider: str, lines: list[str]) -> str:
    header = [
        f"# {provider} broker SDK for the StockMonitor packaged runtime. Not shipped in the installer (Q52):",
        "# install it yourself with install_provider_sdk.ps1 (pip --no-deps, latest from PyPI, no version pin -- the",
        "# bundled runtime already carries every other dependency). Package names generated by",
        "# scripts/tooling/stage_python_runtime.py from requirements/" + PROVIDER_SDK_LOCKS[provider] + ".",
    ]
    return "\n".join(header + lines) + "\n"


def _write_provider_sdk_requirements() -> dict[str, list[str]]:
    directory = STAGE_DIR / "provider_sdk"
    directory.mkdir(parents=True, exist_ok=True)
    requirements = provider_sdk_requirements()
    for provider, lines in requirements.items():
        (directory / f"{provider}.txt").write_text(_provider_sdk_file_text(provider, lines), encoding="utf-8")
    return requirements


def _strip_build_only_artifacts() -> None:
    # pip stays (the user installs the broker SDKs with it), but its console launchers do not: the documented
    # command is `python.exe -m pip`, and the launchers only widen the shipped executable surface.
    for launcher in (STAGE_DIR / "Scripts").glob("pip*.exe"):
        launcher.unlink(missing_ok=True)
    shutil.rmtree(STAGE_DIR / "Lib" / "site-packages" / "bin", ignore_errors=True)
    for cache_dir in list(STAGE_DIR.rglob("__pycache__")):
        shutil.rmtree(cache_dir, ignore_errors=True)
    for log in list(STAGE_DIR.rglob("*.log")):
        log.unlink(missing_ok=True)


def _executables(stage_dir: Path = STAGE_DIR) -> list[str]:
    return sorted(str(p.relative_to(stage_dir)).replace("\\", "/") for p in stage_dir.rglob("*.exe"))


def unexpected_executables(paths: list[str]) -> list[str]:
    allowed_dirs = ["/".join(parts) + "/" for parts in ALLOWED_EXECUTABLE_DIRS]
    return [p for p in paths
            if p not in ALLOWED_EXECUTABLES and not any(p.startswith(prefix) for prefix in allowed_dirs)]


def _verify(python_exe: Path) -> None:
    # Checks the interpreter + third-party packages in isolation. The project's own packages are siblings of
    # app-runtime/python/ only in the final packaged layout; that wiring is exercised by running the dist build.
    probe = STAGE_DIR / "_verify_probe.py"
    probe.write_text(
        "import importlib.util, sys\n"
        "assert not any('AppData' in p and 'Roaming' in p and 'provider-sdk' not in p for p in sys.path), "
        "'host user site-packages leaked into the bundled interpreter: ' + repr(sys.path)\n"
        "import numpy, pandas, pyarrow, fastapi, uvicorn, websockets, sklearn, lightgbm, onnx, onnxruntime, "
        "skl2onnx, onnxmltools\n"
        "bundled_sdk = [n for n in ('shioaji', 'moomoo', 'futu') if importlib.util.find_spec(n)]\n"
        "assert not bundled_sdk, 'broker SDK must not be bundled: ' + repr(bundled_sdk)\n"
        "import pip\n"
        "print('STAGE_PYTHON_RUNTIME_VERIFY_OK')\n",
        encoding="utf-8",
    )
    empty_sdk_dir = tempfile.mkdtemp(prefix="stockmonitor-empty-sdk-")
    try:
        result = subprocess.run(
            [str(python_exe), str(probe)], cwd=STAGE_DIR, capture_output=True, text=True,
            env={**_isolated_env(), "STOCK_MONITOR_PROVIDER_SDK_DIR": empty_sdk_dir}, timeout=180,
        )
    finally:
        probe.unlink(missing_ok=True)
        shutil.rmtree(empty_sdk_dir, ignore_errors=True)
    if result.returncode != 0 or "STAGE_PYTHON_RUNTIME_VERIFY_OK" not in result.stdout:
        raise RuntimeError(
            f"staged runtime failed verification:\nSTDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}")
    unexpected = unexpected_executables(_executables())
    if unexpected:
        raise RuntimeError(f"staged runtime contains executables outside the allowlist: {unexpected}")
    _log("verification passed: isolated from host site-packages, bundled deps importable, no broker SDK, "
         "no unexpected executables")


def _inputs(version: str, provider_sdk: dict[str, list[str]]) -> dict:
    """What a staged runtime is built from: the bootstrap pins, every bundled lock's digest, the provider lists."""
    pins = _pins()
    return {
        "schema": "staged-python-runtime-v1",
        "python": {"version": version, "sha256": pins["python_embed"]["sha256"]},
        "pip": {"version": pins["pip_wheel"]["version"], "sha256": pins["pip_wheel"]["sha256"]},
        "bundled_locks": {name: _sha256(ROOT / "requirements" / name) for name in RUNTIME_LOCKS},
        "provider_sdk_not_bundled": {provider: [line.split()[0] for line in lines]
                                     for provider, lines in provider_sdk.items()},
    }


def _write_manifest(version: str, provider_sdk: dict[str, list[str]]) -> None:
    manifest = {**_inputs(version, provider_sdk), "executables": _executables()}
    (STAGE_DIR / "STAGED_RUNTIME.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def _dist_key(name: str) -> str:
    return re.sub(r"[-_.]+", "_", name).lower()


def check_staged(stage_dir: Path = STAGE_DIR) -> list[str]:
    """The one check that a staged runtime is the one the current pins and locks describe -- used by
    ``--check``, by build_release.py before it reuses packaging/python, and by audit_packaging.cjs (beforePack).
    Returns every problem found; an empty list means current. A directory that merely exists is never enough."""
    problems: list[str] = []
    manifest_path = stage_dir / "STAGED_RUNTIME.json"
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except FileNotFoundError:  # not an error: reported as the problem it is
        return [f"{manifest_path} missing: stage the runtime with stage_python_runtime.py --force"]
    except (OSError, ValueError) as exc:  # not an error: reported as the problem it is
        return [f"{manifest_path} unreadable: {type(exc).__name__}: {exc}"]
    provider_sdk = provider_sdk_requirements()
    expected = _inputs(_target_python_version(), provider_sdk)
    for key, value in expected.items():
        if manifest.get(key) != value:
            problems.append(f"STAGED_RUNTIME.json {key} is {manifest.get(key)!r}, the current pins/locks say {value!r}")
    python_exe = stage_dir / "python.exe"
    if not python_exe.is_file():
        problems.append(f"{python_exe} missing")
    site_packages = stage_dir / "Lib" / "site-packages"
    present = {_dist_key(p.name[:-len(".dist-info")]) for p in site_packages.glob("*.dist-info")} if site_packages.is_dir() else set()
    for line in _locked_requirements():
        name, _, version = line.split()[0].partition("==")
        if _dist_key(f"{name}-{version}") not in present:
            problems.append(f"bundled package {name}=={version} is not what is staged in {site_packages}")
    for distribution in PROVIDER_SDK_DISTRIBUTIONS:
        if any(key.startswith(_dist_key(distribution) + "_") for key in present):
            problems.append(f"broker SDK {distribution} is staged into the installer (Q52 keeps it out)")
    for provider, lines in provider_sdk.items():
        path = stage_dir / "provider_sdk" / f"{provider}.txt"
        try:
            text = path.read_text(encoding="utf-8")
        except FileNotFoundError:  # not an error: reported as the problem it is
            problems.append(f"{path} missing")
            continue
        if text != _provider_sdk_file_text(provider, lines):
            problems.append(f"{path} is not the list requirements/{PROVIDER_SDK_LOCKS[provider]} gives now")
    executables = _executables(stage_dir)
    if executables != manifest.get("executables"):
        problems.append(f"executables on disk {executables} differ from STAGED_RUNTIME.json {manifest.get('executables')}")
    unexpected = unexpected_executables(executables)
    if unexpected:
        problems.append(f"executables outside the allowlist: {unexpected}")
    if list((stage_dir / "Scripts").glob("pip*.exe")):
        problems.append("build-only pip launcher(s) still staged under Scripts/")
    return problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="rebuild even if packaging/python/ already exists")
    parser.add_argument("--check", action="store_true",
                        help="only check that packaging/python is the runtime the current pins and locks describe")
    args = parser.parse_args()

    if args.check:
        problems = check_staged()
        for problem in problems:
            print(f"[stage_python_runtime --check] {problem}", file=sys.stderr, flush=True)
        if not problems:
            _log(f"{STAGE_DIR} is current")
        return 1 if problems else 0

    if STAGE_DIR.exists() and not args.force:
        raise SystemExit(f"{STAGE_DIR} already exists; pass --force to rebuild it from scratch")

    version = _target_python_version()
    _log(f"target interpreter: CPython {version} win_amd64 (pinned in requirements/python-bootstrap.json)")
    python_exe = _stage_interpreter(version)
    _bootstrap_pip(python_exe)
    _pip_install_locked(python_exe)
    provider_sdk = _write_provider_sdk_requirements()
    _strip_build_only_artifacts()
    _verify(python_exe)
    _write_manifest(version, provider_sdk)
    _log(f"staged redistributable runtime at {STAGE_DIR}")


if __name__ == "__main__":
    sys.exit(main())
