"""The installed flavor's per-user directory names, generated from config/var_layout.json "flavors.installed".

var_layout.json is the one authority (AGENTS.md section 2). Three places outside Python and Node need the names:
the NSIS uninstaller (which directories it deletes), install_provider_sdk.ps1 (where it installs a broker SDK) and
the bundled Python's sitecustomize.py (where it reads one). They get them from files written here, never from a
hand-written copy:

  packaging/installed_flavor.nsh   !define lines, included by packaging/installer.nsh
  packaging/installed_flavor.json  read by install_provider_sdk.ps1 (shipped beside it in resources/)

`--write` regenerates both; `--check` (build_release.py, tests) fails when either differs from var_layout.json.
stage_python_runtime.py takes provider_sdk_dir() directly.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VAR_LAYOUT = ROOT / "config" / "var_layout.json"
NSH = ROOT / "packaging" / "installed_flavor.nsh"
JSON_FILE = ROOT / "packaging" / "installed_flavor.json"
SCHEMA = "stock-monitor-installed-flavor-v1"
# The provider SDK root inside the installed flavor's %APPDATA% directory.
PROVIDER_SDK_SUBDIR = "provider-sdk"


def flavor() -> dict:
    """{user_data_dir, auth_root_dir, provider_sdk_dir} of the installed flavor; paths as lists of components."""
    layout = json.loads(VAR_LAYOUT.read_text(encoding="utf-8"))
    installed = layout["flavors"]["installed"]
    user_data_dir = str(installed["user_data_dir"])
    auth_dir = [str(part) for part in installed["auth_dir"]]
    for name in [user_data_dir, *auth_dir]:
        if not name or any(ch in name for ch in '\\/:*?"<>|$;'):
            raise ValueError(f"var_layout.json installed flavor has an unsafe directory name: {name!r}")
    return {"user_data_dir": user_data_dir, "auth_root_dir": auth_dir[0],
            "provider_sdk_dir": [user_data_dir, PROVIDER_SDK_SUBDIR]}


def provider_sdk_dir() -> list[str]:
    """%APPDATA%-relative components of the provider SDK root."""
    return flavor()["provider_sdk_dir"]


def render_nsh(value: dict) -> str:
    return ("; Generated by scripts/tooling/installed_flavor.py from config/var_layout.json -- do not edit.\r\n"
            f'!define STOCKMONITOR_USER_DATA_DIR "{value["user_data_dir"]}"\r\n'
            f'!define STOCKMONITOR_AUTH_ROOT_DIR "{value["auth_root_dir"]}"\r\n')


def render_json(value: dict) -> str:
    document = {"schema": SCHEMA, "generated_from": "config/var_layout.json flavors.installed", **value}
    return json.dumps(document, ensure_ascii=False, indent=2) + "\n"


def stale() -> list[str]:
    value = flavor()
    expected = {NSH: render_nsh(value), JSON_FILE: render_json(value)}
    # Compared line by line: git may check either file out with CRLF or LF.
    same = lambda path, text: path.read_bytes().decode("utf-8").splitlines() == text.splitlines()
    return [str(path.relative_to(ROOT)) for path, text in expected.items() if not path.is_file() or not same(path, text)]


def write() -> None:
    value = flavor()
    NSH.write_bytes(render_nsh(value).encode("utf-8"))
    JSON_FILE.write_bytes(render_json(value).encode("utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        write()
        return 0
    differing = stale()
    if differing:
        print(f"[installed_flavor] out of date with config/var_layout.json: {', '.join(differing)}; "
              "run python scripts/tooling/installed_flavor.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
